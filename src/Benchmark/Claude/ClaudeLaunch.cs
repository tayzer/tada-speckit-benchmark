using System.Text.Json.Nodes;
using Benchmark.Config;
using Benchmark.Runs;
using Benchmark.Util;

namespace Benchmark.Claude;

/// <summary>
/// Builds Claude Code CLI invocations. Both workflows get byte-identical common arguments; the only
/// workflow-specific argument is TADA's --plugin-dir (its documented per-session activation).
/// Never emitted: --bare (disables skills/plugins/hooks discovery), --dangerously-skip-permissions,
/// bypassPermissions.
/// </summary>
public static class ClaudeLaunch
{
    public static readonly string[] ForbiddenArguments = ["--bare", "--dangerously-skip-permissions", "--allow-dangerously-skip-permissions", "bypassPermissions", "--safe-mode"];

    public static List<string> CommonArgs(AgentConfig agent, string runSettingsPath)
    {
        var args = new List<string>
        {
            "--model", agent.Model,
            "--effort", agent.Effort,
            "--setting-sources", agent.SettingSources,
            "--settings", runSettingsPath,
            "--permission-mode", agent.PermissionMode,
        };
        if (!string.IsNullOrWhiteSpace(agent.FallbackModel)) args.AddRange(["--fallback-model", agent.FallbackModel]);
        if (agent.StrictMcpConfig) args.Add("--strict-mcp-config");
        return args;
    }

    public static List<string> WorkflowArgs(WorkflowConfig workflow, string? installedPluginPath) =>
        workflow.Kind == WorkflowKind.Tada && installedPluginPath is not null ? ["--plugin-dir", installedPluginPath] : [];

    public static List<string> SessionArgs(string sessionId, bool resume) => resume ? ["--resume", sessionId] : ["--session-id", sessionId];

    public static List<string> ManagedArgs(AgentConfig agent) =>
        ["-p", "--output-format", "stream-json", "--verbose", "--permission-prompts", agent.PermissionPrompts];

    public static void AssertNoForbidden(IEnumerable<string> args)
    {
        foreach (var a in args)
            if (ForbiddenArguments.Any(f => a.Equals(f, StringComparison.OrdinalIgnoreCase)))
                throw new BenchmarkException($"Refusing to launch Claude Code with forbidden argument '{a}'.");
    }

    /// <summary>
    /// Converts an absolute Windows path to Claude Code's permission-rule form: "//d/Dev/x/**".
    /// (Windows paths are normalised to POSIX form; "//" marks an absolute path. Verified against CLI 2.1.323.)
    /// </summary>
    public static string PermissionPath(string absolutePath)
    {
        var full = Path.GetFullPath(absolutePath).Replace('\\', '/').TrimEnd('/');
        if (full.Length >= 2 && full[1] == ':') full = "/" + char.ToLowerInvariant(full[0]) + full[2..];
        return "/" + full + "/**";
    }

    /// <summary>
    /// The run-specific settings file passed with --settings. Holds the permission policy (identical for
    /// both workflows apart from the absolute paths, which are templated before hashing).
    /// </summary>
    public static (JsonObject Settings, string PolicySha256) BuildRunSettings(AgentConfig agent, IReadOnlyList<string> forbiddenRoots, string workspace)
    {
        var deny = new JsonArray();
        foreach (var rule in agent.DisallowedTools) deny.Add(rule);
        foreach (var root in forbiddenRoots.Where(Path.IsPathRooted))
        {
            var p = PermissionPath(root);
            foreach (var tool in new[] { "Read", "Edit", "Write", "Glob", "Grep" }) deny.Add($"{tool}({p})");
        }
        var allow = new JsonArray();
        foreach (var rule in agent.AllowedTools) allow.Add(rule);
        var settings = new JsonObject
        {
            ["$comment"] = "Generated by the benchmark harness for one run. Do not edit.",
            ["permissions"] = new JsonObject
            {
                ["allow"] = allow,
                ["deny"] = deny,
                ["additionalDirectories"] = new JsonArray(),
            },
        };
        // Hash with run-specific absolute paths replaced, so equivalent policies compare equal across arms.
        var templated = settings.ToJsonString()
            .Replace(PermissionPath(workspace).TrimEnd('*', '/'), "<WORKSPACE>", StringComparison.OrdinalIgnoreCase);
        foreach (var root in forbiddenRoots.Where(Path.IsPathRooted))
            templated = templated.Replace(PermissionPath(root).TrimEnd('*', '/'), "<FORBIDDEN>", StringComparison.OrdinalIgnoreCase);
        var policyHash = Fs.Sha256Text(agent.PermissionMode + "|" + agent.PermissionPrompts + "|" + NormaliseForbiddenCount(templated));
        return (settings, policyHash);
    }

    // Different arms can have a different number of sibling workspaces to deny; collapse duplicates so the
    // policy hash reflects the *kind* of rules, not how many earlier runs exist.
    private static string NormaliseForbiddenCount(string templated)
    {
        var node = JsonNode.Parse(templated)!.AsObject();
        if (node["permissions"]?["deny"] is JsonArray d)
        {
            var distinct = d.Select(x => x!.ToString()).Distinct().OrderBy(x => x, StringComparer.Ordinal).ToList();
            node["permissions"]!["deny"] = new JsonArray(distinct.Select(x => (JsonNode)x!).ToArray());
        }
        return node.ToJsonString();
    }

    /// <summary>
    /// Claude Code stores transcripts under ~/.claude/projects/&lt;cwd with non-alphanumerics replaced by '-'&gt;/.
    /// (Observed on CLI 2.1.323; internal layout, verified at import time.)
    /// </summary>
    public static string ProjectDirName(string cwd)
    {
        var full = Path.GetFullPath(cwd).TrimEnd('\\', '/');
        return new string(full.Select(c => char.IsAsciiLetterOrDigit(c) ? c : '-').ToArray());
    }

    public static string ClaudeConfigDir() =>
        Environment.GetEnvironmentVariable("CLAUDE_CONFIG_DIR") is { Length: > 0 } d ? d : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".claude");

    public static (string Main, List<string> Subagents) TranscriptPaths(string cwd, string sessionId)
    {
        var projectDir = Path.Combine(ClaudeConfigDir(), "projects", ProjectDirName(cwd));
        var main = Path.Combine(projectDir, sessionId + ".jsonl");
        var subDir = Path.Combine(projectDir, sessionId, "subagents");
        var subs = Directory.Exists(subDir) ? Directory.GetFiles(subDir, "*.jsonl").OrderBy(f => f, StringComparer.Ordinal).ToList() : [];
        return (main, subs);
    }

    /// <summary>Environment variables set for every agent process (identical for both workflows apart from paths).</summary>
    public static Dictionary<string, string?> AgentEnvironment(AgentConfig agent, string nugetPackages)
    {
        var env = new Dictionary<string, string?>
        {
            ["NUGET_PACKAGES"] = nugetPackages,
            ["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1",
            ["DOTNET_NOLOGO"] = "1",
            ["DOTNET_SKIP_FIRST_TIME_EXPERIENCE"] = "1",
            // The effort env var outranks --effort; clear it so the configured flag is the effective setting.
            ["CLAUDE_CODE_EFFORT_LEVEL"] = null,
            ["ANTHROPIC_MODEL"] = null,
            // Keep benchmark sessions from updating Claude Code between or during runs.
            ["DISABLE_AUTOUPDATER"] = "1",
        };
        foreach (var (k, v) in agent.Environment) env[k] = v;
        return env;
    }
}
